def b_kaprekar_num(n):
    res = []
    for m in range(1, n + 1):
        sq = m * m
        for k in range(1, len(str(sq)) + 1):
            right = sq % 10 ** k
            left = sq // 10 ** k
            if right > 0 and left + right == m:
                res.append(m)
                break
    return res


