def b_self_describing(d):
    out = []
    for digs in product(range(d + 1), repeat=d):
        if sum(digs) != d or digs[0] == 0:
            continue
        if all(digs[i] == digs.count(i) for i in range(d)):
            out.append(int("".join(map(str, digs))))
    return out


