def b_kaprekar(n):
    d = [n // 1000, n // 100 % 10, n // 10 % 10, n % 10]
    if d[0] == d[1] == d[2] == d[3]:
        return -1
    steps = 0
    x = n
    while x != 6174 and steps < 100:
        d = [x // 1000, x // 100 % 10, x // 10 % 10, x % 10]
        hi = sorted(d, reverse=True)
        lo = sorted(d)
        x = (hi[0] * 1000 + hi[1] * 100 + hi[2] * 10 + hi[3]) - (lo[0] * 1000 + lo[1] * 100 + lo[2] * 10 + lo[3])
        steps += 1
    return steps


